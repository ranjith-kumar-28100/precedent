"""Write src/mock/data.ts from ../data/*.json with PUBLIC fields only (never ship hidden simulator profiles)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2] / "data"
vendors = json.loads((root / "vendors.json").read_text())
history = json.loads((root / "history.json").read_text())
upcoming = json.loads((root / "upcoming.json").read_text())
evalc = json.loads((root / "eval_cache.json").read_text())
n = {}
for e in history:
    n[e["vendor_id"]] = n.get(e["vendor_id"], 0) + 1
pub = [{k: v[k] for k in ("id", "name", "category", "contact", "list_price_usd_annual")} | {"episodes": n.get(v["id"], 0)} for v in vendors]
out = pathlib.Path(__file__).resolve().parents[1] / "src" / "mock" / "data.ts"
out.write_text("// Generated by scripts/gen-mock-data.py from data/*.json (public fields only).\n"
               f"export const VENDORS = {json.dumps(pub, indent=1)}\n"
               f"export const HISTORY = {json.dumps(history, indent=1)}\n"
               f"export const UPCOMING = {json.dumps(upcoming, indent=1)}\n"
               f"export const EVAL = {json.dumps(evalc)}\n")
print("wrote", out)
